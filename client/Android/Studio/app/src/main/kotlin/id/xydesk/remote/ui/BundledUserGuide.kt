Mulai koneksi
Tambahkan perangkat dengan alamat, port, dan akun Windows yang memang boleh kamu akses. Kredensial jangan dikirim ke Chat Global atau feed. Tekan Connect, lalu perhatikan status loading dan pesan kesalahan; koneksi baru berhasil ketika frame sesi tampil.

Mikrofon & audio
Berikan izin mikrofon Android bila diminta dan periksa pilihan audio sesi. Untuk RDP, Windows juga harus mengizinkan pengalihan perekaman audio. Sakelar ON saja bukan bukti bahwa suara sudah diterima Windows.

Chat & channel resmi
Chat Global dipakai untuk percakapan komunitas. #PanduanPengguna berisi panduan, #Informasi berisi informasi layanan, dan #Announcement untuk pengumuman. Tekan tag untuk membuka channel. Hanya admin, founder, atau tim yang diberi akses server yang dapat menerbitkan pesan resmi.

Scroll & suara
Saat membaca pesan lama, pesan masuk tidak menarik layar ke bawah. Gunakan tombol ke bawah/indikator pesan baru untuk kembali ke percakapan terbaru. Suara kirim menandakan konfirmasi server, bukan sekadar pesan masih dalam antrean. Mode senyap dan Jangan Ganggu tetap dihormati.

Bila ada kendala
Jangan menghapus data atau uninstall untuk mengatasi layar hitam sebelum cadangan dan pemulihannya terverifikasi. Simpan waktu kejadian, jenis koneksi, dan error yang muncul; jangan sertakan password, token, atau data pribadi dalam laporan. Lihat #Informasi untuk status layanan dan #Announcement untuk pengumuman resmi.
